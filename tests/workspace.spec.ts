import { expect, test } from '@playwright/test'

test('hội thoại, đính kèm và bàn giao tồn tại sau khi tải lại',async ({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Hội thoại mới',exact:true}).click()
  await page.locator('input[type=file]').setInputFiles({name:'yeu-cau.txt',mimeType:'text/plain',buffer:Buffer.from('Mô tả yêu cầu')})
  await page.getByLabel('Nội dung WorkChat').fill('Lưu bối cảnh xây dựng giao diện')
  await page.getByRole('button',{name:'Lưu ghi chú'}).click()
  await expect(page.getByText('Lưu bối cảnh xây dựng giao diện')).toBeVisible()
  await page.getByRole('button',{name:'Bàn giao',exact:true}).click()
  await page.getByLabel('Nhà cung cấp AI').selectOption('claude')
  await page.getByLabel('Nội dung WorkChat').fill('Xây dựng giao diện WorkChat')
  await page.getByRole('button',{name:'Tạo gói bàn giao'}).click()
  await expect(page.getByText('Bàn giao · Claude')).toBeVisible()
  await expect(page.getByRole('link',{name:'Mở Claude'})).toHaveAttribute('href', 'https://www.anthropic.com/claude-code')
  await page.getByRole('button',{name:'Nhập kết quả'}).click()
  await page.getByLabel('Kết quả, tiêu chí đã kiểm tra hoặc liên kết Pull Request').fill('Đã kiểm tra trên desktop')
  await page.getByRole('button',{name:'Lưu',exact:true}).click()
  await page.reload()
  await page.getByRole('button',{name:'Cuộc trò chuyện mới',exact:true}).click()
  await expect(page.getByText('Đã kiểm tra trên desktop')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button',{name:'yeu-cau.txt'}).click()
  expect((await download).suggestedFilename()).toBe('yeu-cau.txt')
})
test('trên màn hình 390 px, tạo task, nghiệm thu và kiểm tra tiến độ',async ({page})=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  await expect(page.getByRole('heading',{name:/Tập trung/})).toBeVisible()
  expect(await page.locator('body').evaluate(el=>el.scrollWidth)).toBe(390)
  await page.getByRole('button',{name:'Giao việc',exact:true}).click()
  await page.getByLabel('Nội dung WorkChat').fill('Kiểm tra bản xem thử')
  await page.getByRole('button',{name:'Tạo nhiệm vụ',exact:true}).click()
  await page.getByLabel('Tiêu chí nghiệm thu').fill('Kiểm tra được trên màn hình 390 px')
  await page.getByLabel('Trọng số').fill('2')
  await page.getByRole('button',{name:'Lưu',exact:true}).click()
  await page.getByRole('button',{name:'Mở điều hướng'}).click()
  await page.getByRole('button',{name:'Dự án',exact:true}).click()
  await page.getByLabel('Trạng thái Kiểm tra bản xem thử').selectOption('accepted')
  await page.getByRole('button',{name:'Mở điều hướng'}).click()
  await page.getByRole('button',{name:'Dashboard',exact:true}).click()
  await expect(page.getByText('50%',{exact:true})).toBeVisible()
})
test('tắt nhà cung cấp và hiển thị đúng nguồn dữ liệu',async ({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Mô hình AI',exact:true}).click()
  await page.getByRole('switch',{name:'Bật ChatGPT'}).click()
  await expect(page.getByRole('switch',{name:'Bật ChatGPT'})).toHaveAttribute('aria-checked','false')
  await page.getByRole('button',{name:'WorkChat',exact:true}).click()
  await expect(page.getByLabel('Nhà cung cấp AI')).toHaveValue('claude')
  await page.getByRole('button',{name:'Dashboard',exact:true}).click()
  await page.getByRole('button',{name:'Nhập số liệu'}).click()
  await page.getByLabel('Token',{exact:true}).fill('100')
  await page.getByRole('combobox',{name:'Nguồn',exact:true}).selectOption('estimate')
  await page.getByRole('button',{name:'Lưu',exact:true}).click()
  await expect(page.getByText('Ước lượng',{exact:true})).toBeVisible()
  await expect(page.getByText('100 token',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Hoạt động',exact:true}).click()
  await expect(page.getByText('Tắt ChatGPT')).toBeVisible()
})
